package handbook.compose.composition

/**
 * Учебный элемент композиции — то, что эмитится в цикле (`items.forEach { … }`) и получает свой
 * «слот» в slot table.
 *
 * В Compose состояние (`remember`, `mutableStateOf`) хранится в slot table и привязывается к
 * composable по его **позиции** в дереве вызовов (positional memoization). У элемента списка позиция
 * — это индекс. Если список переупорядочить/вставить/удалить без `key()`, позиции «съедут», и слот
 * (а с ним `remember`-состояние) окажется привязан не к тому элементу. `key(id) { … }` даёт элементу
 * СТАБИЛЬНУЮ идентичность (по [id]), не зависящую от позиции.
 *
 * Здесь мы сводим композицию к списку элементов с id и их слот-состоянием и детерминированно
 * моделируем, что Compose переиспользует, а что теряет — с ключами и без.
 *
 * @property id стабильный ключ элемента (то, что передают в `key(id)`).
 * @property state значение, лежащее в слоте этого элемента (аналог `remember`-состояния).
 */
data class Item(val id: String, val state: Any? = null)
