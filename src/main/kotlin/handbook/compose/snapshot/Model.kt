package handbook.compose.snapshot

/**
 * Версионированная запись значения состояния — учебный аналог `StateRecord` в MVCC-модели Compose.
 *
 * Каждое `MutableState` хранит НЕ одно значение, а цепочку записей: кто (какой снапшот/версия) и
 * какое значение записал. Чтение из снапшота версии V возвращает запись с наибольшей [version],
 * которая `<= V` (и не принадлежит отменённому снапшоту). Так разные снапшоты одновременно видят
 * РАЗНЫЕ, но каждый — консистентные значения одного и того же состояния (snapshot isolation).
 *
 * @property version номер снапшота (глобальная версия), записавшего это значение.
 * @property value само значение.
 */
data class Record(val version: Int, val value: Any?)

/**
 * Результат `snapshot.apply()` — попытки опубликовать записи снапшота в глобальное состояние.
 *  • [SUCCESS] — конфликтов нет, записи применены как есть;
 *  • [MERGED] — был конфликт, но политика состояния (`SnapshotMutationPolicy.merge`) свела значения;
 *  • [FAILURE] — конфликт неразрешим: apply отклонён целиком (атомарно), изменения снапшота отброшены.
 */
enum class ApplyResult { SUCCESS, MERGED, FAILURE }
