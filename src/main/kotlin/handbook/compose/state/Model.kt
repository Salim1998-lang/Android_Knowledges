package handbook.compose.state

/**
 * Учебная модель одного слота `remember` в slot table.
 *
 * В реальном Compose `remember { … }` кэширует результат по **позиции вызова** в slot table: при
 * первой композиции лямбда выполняется и значение сохраняется, при рекомпозиции — возвращается
 * закэшированное (лямбда НЕ вызывается). У `remember(key1, key2) { … }` есть ключи: если хоть один
 * ключ структурно изменился — кэш сбрасывается и лямбда пересчитывается заново.
 *
 * Здесь слот моделируется парой (ключи, значение); мы прогоняем последовательности (ре)композиций и
 * детерминированно проверяем, что пересчиталось, а что переиспользовалось.
 *
 * @property keys аргументы-ключи `remember(k1, k2) { … }`; пустой список — `remember { … }` без ключей.
 * @property value закэшированное значение слота.
 */
data class Slot(
    val keys: List<Any?>,
    val value: Any?,
)

/**
 * События, которые состояние может (не) пережить.
 *  • [RECOMPOSE] — обычная рекомпозиция (то же дерево, тот же экземпляр композиции);
 *  • [CONFIG_CHANGE] — смена конфигурации (поворот и т.п.): Activity/композиция пересоздаётся;
 *  • [PROCESS_DEATH] — система убила процесс в фоне и восстановила экран из savedInstanceState.
 *
 * `remember` переживает только [RECOMPOSE]. `rememberSaveable` (если значение сохраняемо) переживает
 * все три — оно кладётся в `Bundle` savedInstanceState.
 */
enum class SurvivalEvent { RECOMPOSE, CONFIG_CHANGE, PROCESS_DEATH }
